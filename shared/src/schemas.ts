import { z } from 'zod';

export const eventTypeSchema = z.enum([
  'wedding',
  'birthday',
  'anniversary',
  'community',
  'engagement',
  'baby_shower',
  'corporate_gala',
  'other',
]);

export const venuePreferenceSchema = z.enum([
  'indoor',
  'outdoor',
  'beach',
  'banquet',
  'home',
  'flexible',
]);

export const taskPhaseSchema = z.enum([
  '3-6 months before',
  '1-2 months before',
  '2-4 weeks before',
  'Week of event',
  'Event day',
  'Post-event',
]);

export const taskPrioritySchema = z.enum(['low', 'medium', 'high', 'critical']);

export const vendorStatusSchema = z.enum(['research', 'shortlisted', 'contacted', 'booked']);

// Input validation schema for generating a plan or creating an event
export const eventRequirementsSchema = z.object({
  id: z.string().optional(),
  title: z
    .string()
    .trim()
    .min(3, { message: 'Title must be at least 3 characters long' })
    .max(100, { message: 'Title cannot exceed 100 characters' }),
  eventType: eventTypeSchema,
  eventDate: z
    .string()
    .regex(/^\d{4}-\d{2}-\d{2}$/, { message: 'Date must be formatted as YYYY-MM-DD' }),
  city: z
    .string()
    .trim()
    .min(2, { message: 'City/Location must be at least 2 characters' })
    .max(100, { message: 'City cannot exceed 100 characters' }),
  guestCount: z
    .number()
    .int({ message: 'Guest count must be an integer' })
    .min(1, { message: 'Guest count must be at least 1' })
    .max(50000, { message: 'Guest count cannot exceed 50,000' }),
  budget: z
    .number()
    .positive({ message: 'Budget must be greater than zero' })
    .max(1000000000, { message: 'Budget exceeds maximum permitted limit' }),
  currency: z
    .string()
    .trim()
    .min(1)
    .max(5)
    .default('INR'),
  themePreference: z.string().trim().max(200).optional().default(''),
  venuePreference: venuePreferenceSchema.default('indoor'),
  dietaryPreferences: z.array(z.string().trim().max(50)).default([]),
  additionalInstructions: z.string().trim().max(1000).optional().default(''),
});

export const budgetItemSchema = z.object({
  id: z.string(),
  category: z.string().min(1),
  estimatedAmount: z.number().nonnegative(),
  actualAmount: z.number().nonnegative().default(0),
  notes: z.string().optional().default(''),
  isCustom: z.boolean().optional().default(false),
});

export const taskItemSchema = z.object({
  id: z.string(),
  title: z.string().min(1),
  category: z.string().min(1),
  phase: taskPhaseSchema,
  dueDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  completed: z.boolean().default(false),
  priority: taskPrioritySchema.default('medium'),
  notes: z.string().optional().default(''),
});

export const vendorCategorySchema = z.object({
  id: z.string(),
  category: z.string().min(1),
  status: vendorStatusSchema.default('research'),
  vendorName: z.string().default(''),
  contactPerson: z.string().default(''),
  phone: z.string().default(''),
  email: z.string().default(''),
  estimatedBudget: z.number().nonnegative().default(0),
  actualCost: z.number().nonnegative().default(0),
  notes: z.string().optional().default(''),
  questionsToAsk: z.array(z.string()).default([]),
});

// Strict schema to validate output generated by Gemini
export const generatedPlanSchema = z.object({
  eventTitle: z.string().min(1),
  summary: z.string().min(10),
  planningAssumptions: z.array(z.string()).min(1),
  recommendedTheme: z.object({
    name: z.string(),
    colorPalette: z.array(z.string()),
    vibeDescription: z.string(),
    decorConcepts: z.array(z.string()),
  }),
  budgetItems: z.array(budgetItemSchema).min(3),
  contingencyReserve: z.object({
    amount: z.number().nonnegative(),
    percentage: z.number().nonnegative(),
    rationale: z.string(),
  }),
  timeline: z.array(taskItemSchema).min(4),
  vendorCategories: z.array(vendorCategorySchema).min(3),
  personalizedIdeas: z.object({
    entertainment: z.array(z.string()),
    diningExperience: z.array(z.string()),
    guestExperience: z.array(z.string()),
    ecoFriendlyTips: z.array(z.string()),
  }),
  riskAndContingencies: z.array(
    z.object({
      risk: z.string(),
      mitigation: z.string(),
      severity: z.enum(['low', 'medium', 'high']),
    })
  ),
  isDemoPlan: z.boolean().default(false),
  generatedAt: z.string(),
  modelUsed: z.string(),
});

// Update event schema
export const updateEventSchema = z.object({
  requirements: eventRequirementsSchema.optional(),
  plan: generatedPlanSchema.optional(),
});
